import fs from "node:fs/promises";
import path from "node:path";

const repository = "https://github.com/MohamedBayan/AHA-MEMES-sample";
const rawRoot = "https://raw.githubusercontent.com/MohamedBayan/AHA-MEMES-sample/main";
const response = await fetch(`${rawRoot}/data/train_sample.jsonl`);
if (!response.ok) throw new Error(`AHA-MEMES sample download failed: ${response.status}`);

const rows = (await response.text()).trim().split(/\r?\n/u).map(line => JSON.parse(line));
if (rows.length !== 100) throw new Error(`Expected 100 AHA-MEMES sample rows, received ${rows.length}`);
if (new Set(rows.map(row => row.id)).size !== rows.length) throw new Error("Duplicate AHA-MEMES image IDs found");
if (rows.filter(row => row.label === "Hateful").length !== 35) throw new Error("Unexpected AHA-MEMES label distribution");

const items = rows.map(row => `  { id: ${JSON.stringify(`aha-${row.id}`)}, filename: ${JSON.stringify(row.id)}, url: ${JSON.stringify(`${rawRoot}/data/img/${row.id}`)}, sensitive: ${row.label === "Hateful"} },`).join("\n");
const output = `// Generated by scripts/import-aha-memes.mjs from the complete public 100-image sample.\n// The sensitive flag mirrors the source's binary Hateful label. See MEME-SOURCES.md.\nexport const memeSource = ${JSON.stringify(repository)};\n\nexport const sourceMemes = [\n${items}\n] as const;\n`;
await fs.writeFile(path.resolve("packages/fun/src/source-memes.ts"), output, "utf8");
console.log(`Wrote all ${rows.length} public AHA-MEMES sample images`);
