import fs from "node:fs/promises";
import path from "node:path";

const sourceUrl = "https://raw.githubusercontent.com/iwan-rg/Arabic-Humor/main/humor.tsv";
const outputPath = path.resolve("packages/fun/src/arabic-humor.ts");
const response = await fetch(sourceUrl);
if (!response.ok) throw new Error(`Arabic-Humor download failed: ${response.status}`);

function clean(value) {
  return value.normalize("NFKC").replace(/\s+/gu, " ").trim();
}

const rows = (await response.text()).replace(/^\uFEFF/, "").split(/\r?\n/u).slice(1);
const jokes = [];
for (const row of rows) {
  const firstTab = row.indexOf("\t");
  const lastTab = row.lastIndexOf("\t");
  if (firstTab < 0 || lastTab <= firstTab || row.slice(lastTab + 1).trim() !== "yes") continue;
  const id = row.slice(0, firstTab).trim();
  const text = clean(row.slice(firstTab + 1, lastTab));
  if (!id || !text) throw new Error(`Invalid humorous row: ${id || "missing id"}`);
  jokes.push({ id, text });
}

if (jokes.length !== 4455) throw new Error(`Expected 4455 humorous rows, received ${jokes.length}`);
if (new Set(jokes.map(({ id }) => id)).size !== jokes.length) throw new Error("Duplicate humor IDs found");

const lines = jokes.map(({ id, text }) => `  { id: ${JSON.stringify(`arabic-humor-${id}`)}, text: ${JSON.stringify(text)} },`).join("\n");
const output = `// Generated by scripts/import-arabic-humor.mjs\n// All rows labelled "yes" in Arabic-Humor (Al-Khalifa et al., 2022; CC BY 4.0).\n// https://github.com/iwan-rg/Arabic-Humor\nexport type ArabicHumorEntry = { id: string; text: string };\n\nexport const arabicHumor: readonly ArabicHumorEntry[] = [\n${lines}\n];\n`;
await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(outputPath, output, "utf8");
console.log(`Wrote all ${jokes.length} humorous entries to ${outputPath}`);
