import fs from "node:fs/promises";
import path from "node:path";

const sourceUrl = "https://raw.githubusercontent.com/iwan-rg/Arabic-Humor/main/humor.tsv";
const outputPath = path.resolve("packages/fun/src/arabic-humor.ts");
const response = await fetch(sourceUrl);
if (!response.ok) throw new Error(`Arabic-Humor download failed: ${response.status}`);

const forbidden = /(?:https?:\/\/|www\.|@\w|#\w|سياس|انتخاب|انتفاض|اقص[ىي]|رئيس|وزير|حزب|داعش|يهود|نصران|مسلم|شيع|سني|الله|رب[هيك]?|نبي|رسول|قرآن|دين|صلاة|نار|سعود|مصر|سور|لبنان|اردن|فلسط|عراق|كويت|قطر|امارات|يمن|جزائر|مغرب|تونس|سودان|هند|باكستان|امريك|اسرائ|صعيد|بدوي|حوطي|خليلي|حلبي|بركاني|حضرمي|جنس|سكس|عاهر|شرموط|قحبة|منيك|زب|كس|طيز|عور|خنيث|لوطي|مثلي|اغتصاب|حامل|فازلين|سمين|مخدر|حشيش|حشاش|محشش|مبوق|مساطيل|سكران|خمر|يشموا|انتحار|رما نفسه|قتل|ذبح|موت|مات|ميت|وفا[هة]|جثة|استشهاد|انفجار|دم|مجرم|شرط[ية]|بوليس|ظابط|قاضي|محكم|سجن|خطف|عصاب|سكين|مسدس|رصاص|ضرب|صفع|شلبوق|اعمى|اطرش|معاق|متخلف|اسود|عبد|حيوان|كلب|حمار|غبي|بقرة|قرد|خنزير)/iu;
const jokeCue = /(?:مرة|واحد|وحدة|راح|قال|سأل|سالت|دخل|اتصل|مدرس|طالب|دكتور|مطعم|موظف|بخيل|نسي|ليش|ليه|لأنه|عشان|جاوب|رد)/u;
const arabic = /[\u0600-\u06ff]/gu;

function clean(value) {
  return value
    .replace(/[ـًٌٍَُِّْ]/gu, "")
    .replace(/[“”«»]/gu, '"')
    .replace(/\s+/gu, " ")
    .replace(/^[\s.,،:؛!?؟_-]+|[\s_-]+$/gu, "")
    .trim();
}

function normalize(value) {
  return value.toLowerCase().replace(/[إأآ]/gu, "ا").replace(/ى/gu, "ي").replace(/ة/gu, "ه").replace(/[^\p{L}\p{N}]/gu, "");
}

const rows = (await response.text()).replace(/^\uFEFF/, "").split(/\r?\n/u).slice(1);
const seen = new Set();
const candidates = [];
for (const row of rows) {
  const firstTab = row.indexOf("\t");
  const lastTab = row.lastIndexOf("\t");
  if (firstTab < 0 || lastTab <= firstTab || row.slice(lastTab + 1).trim() !== "yes") continue;
  const id = row.slice(0, firstTab).trim();
  const text = clean(row.slice(firstTab + 1, lastTab));
  const letters = text.match(arabic)?.length ?? 0;
  if (text.length < 38 || text.length > 230 || letters / text.length < 0.55 || forbidden.test(text)) continue;
  if (!jokeCue.test(text) || /(.)\1{5,}/u.test(text)) continue;
  const key = normalize(text);
  if (key.length < 28 || seen.has(key)) continue;
  seen.add(key);
  const dialogue = (text.match(/(?:قال|رد|سأل|ليش|ليه)/gu)?.length ?? 0);
  const score = dialogue * 4 + (text.length >= 60 && text.length <= 170 ? 4 : 0) + (/[؟?!]/u.test(text) ? 2 : 0);
  candidates.push({ id, text, score });
}

const selected = candidates.sort((a, b) => b.score - a.score || Number(a.id) - Number(b.id)).slice(0, 650);
if (selected.length < 500) throw new Error(`Only ${selected.length} safe Arabic humor entries passed filtering`);
const lines = selected.map(({ id, text }) => `  { id: ${JSON.stringify(`arabic-humor-${id}`)}, text: ${JSON.stringify(text)} },`).join("\n");
const output = `// Generated by scripts/import-arabic-humor.mjs\n// Source: Arabic-Humor by Iwan and A. Islam (CC BY 4.0)\n// https://github.com/iwan-rg/Arabic-Humor\nexport type ArabicHumorEntry = { id: string; text: string };\n\nexport const arabicHumor: readonly ArabicHumorEntry[] = [\n${lines}\n];\n`;
await fs.mkdir(path.dirname(outputPath), { recursive: true });
await fs.writeFile(outputPath, output, "utf8");
console.log(`Wrote ${selected.length} filtered Arabic humor entries to ${outputPath}`);
