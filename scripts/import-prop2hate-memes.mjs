import fs from "node:fs/promises";
import path from "node:path";

const dataset = "QCRI/Prop2Hate-Meme";
const apiRoot = `https://datasets-server.huggingface.co/rows?dataset=${encodeURIComponent(dataset)}&config=default`;
const splitTotals = { train: 2143, dev: 312, test: 606 };
const jobs = [];
for (const [split, total] of Object.entries(splitTotals)) {
  for (let offset = 0; offset < total; offset += 100) jobs.push({ split, offset, length: Math.min(100, total - offset) });
}

const chunks = await Promise.all(jobs.map(async ({ split, offset, length }) => {
  const response = await fetch(`${apiRoot}&split=${split}&offset=${offset}&length=${length}`);
  if (!response.ok) throw new Error(`Prop2Hate rows failed for ${split}:${offset}: ${response.status}`);
  return { split, payload: await response.json() };
}));

const memes = chunks.flatMap(({ split, payload }) => payload.rows
  .filter(({ row }) => row.prop_label === 0 && row.hate_label === 0 && row.hate_fine_grained_label === 1)
  .map(({ row_idx: rowIndex, row }) => ({ id: `prop2hate-${split}-${rowIndex}`, split, rowIndex, sourceId: row.id })));

memes.sort((a, b) => a.split.localeCompare(b.split) || a.rowIndex - b.rowIndex);
if (memes.length !== 1957) throw new Error(`Expected 1957 safe humor memes, received ${memes.length}`);
if (new Set(memes.map(({ id }) => id)).size !== memes.length) throw new Error("Duplicate Prop2Hate meme IDs found");

const lines = memes.map(meme => `  ${JSON.stringify(meme)},`).join("\n");
const output = `// Generated by scripts/import-prop2hate-memes.mjs.\n// Selection: not_propaganda + not-hateful + humor. See MEME-SOURCES.md.\nexport const prop2HateSource = "https://huggingface.co/datasets/QCRI/Prop2Hate-Meme";\nexport type Prop2HateMeme = { id: string; split: "train" | "dev" | "test"; rowIndex: number; sourceId: string };\nexport const prop2HateMemes: readonly Prop2HateMeme[] = [\n${lines}\n];\n`;
await fs.writeFile(path.resolve("packages/fun/src/prop2hate-memes.ts"), output, "utf8");
console.log(`Wrote ${memes.length} safe Arabic humor memes`);
