export function pickFresh<T extends {id:string}>(bank:readonly T[],recent:readonly string[],random=Math.random):T{
 if(!bank.length)throw new Error('Empty content bank');
 const unseen=bank.filter(item=>!recent.includes(item.id));
 if(unseen.length)return unseen[Math.min(unseen.length-1,Math.max(0,Math.floor(random()*unseen.length)))];
 return [...bank].sort((a,b)=>recent.indexOf(b.id)-recent.indexOf(a.id))[0];
}
